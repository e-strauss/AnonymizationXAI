import re
import math
import torch
from transformers import AutoTokenizer, AutoModelForCausalLM

# ------------------------
# Load TinyLLaMA Model
# ------------------------
model_name = "TinyLlama/TinyLlama-1.1B-Chat-v1.0"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForCausalLM.from_pretrained(model_name)
model.eval()

if torch.backends.mps.is_available():
    device = torch.device("mps")
elif torch.cuda.is_available():
    device = torch.device("cuda")
else:
    device = torch.device("cpu")

# ------------------------
# Clean [[brackets]]
# ------------------------
def remove_double_brackets_keep_content(text):
    return re.sub(r"\[\[|\]\]", "", text)

# ------------------------
# Perplexity Computation
# ------------------------
def calculate_perplexity(text):
    inputs = tokenizer(text, return_tensors="pt", truncation=True, max_length=512)
    inputs = {k: v.to(model.device) for k, v in inputs.items()}
    with torch.no_grad():
        outputs = model(**inputs, labels=inputs["input_ids"])
    loss = outputs.loss
    return math.exp(loss.item())

# ------------------------
# Extract Attacked Texts
# ------------------------
texts = []
with open("TextAttack final results/bert_bertattack_log.txt", "r", encoding="utf-8") as f:
    lines = f.read().splitlines()

collecting = False
line_counter = 0

for line in lines:
    if "--> [[[FAILED]]]" in line:
      continue
    elif "-->" in line:
        collecting = True
        line_counter = 0
    elif collecting:
        line_counter += 1
        if line_counter == 2:
            cleaned_text = remove_double_brackets_keep_content(line.strip())
            texts.append(cleaned_text)
            collecting = False

print(f"\n Collected {len(texts)} failed attack texts.")

# ------------------------
# Evaluate Perplexity
# ------------------------
perplexities = []
for i, text in enumerate(texts, 1):
    try:
        ppl = calculate_perplexity(text)
        perplexities.append(ppl)
        print(f"Example {i} - Perplexity: {ppl:.2f}")
    except Exception as e:
        print(f"Example {i} - Error: {e}")

# ------------------------
# Average Perplexity
# ------------------------
if perplexities:
    avg_ppl = sum(perplexities) / len(perplexities)
    print(f"\n Average Perplexity (TinyLLaMA): {avg_ppl:.2f}")
else:
    print("\n No valid texts to compute perplexity.")

