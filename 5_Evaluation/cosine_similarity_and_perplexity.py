import tensorflow_hub as hub
import numpy as np
import re

def remove_double_brackets_keep_content(text):
    return re.sub(r"\[\[|\]\]", "", text)

def cosine_similarity(vec1, vec2):
    return np.inner(vec1, vec2)

# Load USE model
embed = hub.load("https://tfhub.dev/google/universal-sentence-encoder/4")

# Read file
with open("TextAttack final results/bert_bertattack_log.txt", "r", encoding="utf-8") as f:
    lines = f.read().splitlines()

results = []
text1, text2 = "", ""
collecting_text = False

for line in lines:
    if "--> [[[FAILED]]]" in line:
        continue  # skip failed examples
    elif "-->" in line:
        collecting_text = True
        current_result = {"meta": line.strip(), "text1": "", "text2": ""}
        continue
    elif collecting_text and not current_result["text1"]:
        current_result["text1"] = line.strip()
    elif collecting_text and not current_result["text2"]:
        current_result["text2"] = line.strip()
        results.append(current_result)
        collecting_text = False  # done collecting this example
similarities = []
# Evaluate all valid results
for idx, r in enumerate(results, start=1):
    clean1 = remove_double_brackets_keep_content(r["text1"])
    clean2 = remove_double_brackets_keep_content(r["text2"])
    embeddings = embed([clean1, clean2])
    similarity = cosine_similarity(embeddings[0], embeddings[1])
    similarities.append(similarity)
    print(f"\n--- Example {idx} ---")
    print(r["meta"])
    print(f"Similarity Score (USE): {similarity:.4f}")


